"""Regenerate materials/catalog.py from Oscar's "Solicitud de materiales" master checklist (xlsx).

    python3 scripts/gen_materials_catalog.py "<path to Solicitud de materiales.xlsx>"

Only the master list itself is kept (section, group, name, unit); the quantities, comments and
dealer marks in the sheet belong to one project. Names that follow a pattern (cables by gauge and
colour, conduit parts by trade size, fuses and breakers by rating) are tagged with `kind` and
`attrs` so the rules can find them without string matching in the engine.
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

import openpyxl

OUT = Path(__file__).resolve().parent.parent / "materials" / "catalog.py"
SECTIONS = ("Paneles solares", "Victron Energy", "Generales")
TRADE = r'(\d+(?: \d/\d)?|\d/\d)\s*["”″]'


def slug(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def tag(group: str, name: str) -> tuple[str | None, dict]:
    n = name.strip()
    if m := re.match(r"Cable #?\s*(\S+) AWG - SOLAR (\w+)", n):
        return "cable_solar", {"gauge": m[1], "color": m[2]}
    if m := re.match(r"Cable #?\s*(\S+) AWG THHN, CU, color (\w+)", n):
        return "cable_thhn", {"gauge": m[1], "color": m[2]}
    if m := re.match(r"Cable#? ?(\S+) AWG XHH/XHHW-2.*color (\w+)", n):
        return "cable_xhhw", {"gauge": m[1], "color": m[2]}
    if m := re.match(r"Conector de ojo para cable #(\S+) AWG", n):
        return "lug", {"gauge": m[1]}
    if m := re.match(r"Termoencogible para cable #(\S+) (\w+)", n):
        return "shrink", {"gauge": m[1], "color": m[2]}
    if m := re.match(r"Tape color (\w+)", n):
        return "tape", {"color": m[1]}
    if m := re.match(r"Fusible Mega (\d+)A", n):
        return "fuse_mega", {"amps": int(m[1])}
    if m := re.match(r"Breaker DC para riel DIN (\d+)A (\d)P", n):
        return "breaker_dc_din", {"amps": int(m[1]), "poles": int(m[2])}
    if m := re.match(r"Breaker AC para riel DIN (\d+)A (\d)P", n):
        return "breaker_ac_din", {"amps": int(m[1]), "poles": int(m[2])}
    if m := re.match(r"Breaker de (\d+)A (\d) polos", n):
        return "breaker_panel", {"amps": int(m[1]), "poles": int(m[2])}
    mat = "PVC" if "PVC" in group else "EMT" if "EMT" in group else "BIEX" if "Biex" in group else None
    if mat:
        for kind, pat in (("conduit_tube", r"Tuber[ií]a " + TRADE), ("conduit_union", r"Uniones de " + TRADE),
                          ("conduit_press_connector", r"Conector de presi[oó]n " + TRADE),
                          ("conduit_connector", r"Conector " + TRADE), ("conduit_bend", r"Curva de " + TRADE),
                          ("conduit_strap", r"Gasa channel " + TRADE), ("conduit_lb", r"Conduleta LB " + TRADE)):
            if m := re.match(pat, n):
                return kind, {"material": mat, "trade": m[1]}
    return None, {}


def main(path: str) -> None:
    ws = openpyxl.load_workbook(path, data_only=True).active
    rows, section, group, used = [], None, None, set()
    for r in ws.iter_rows(min_row=2, values_only=True):
        name = (r[0] or "").strip() if isinstance(r[0], str) else ""
        if not name:
            continue
        if r[1] == "Cantidad":                       # a section header row
            section, group = name, None
            continue
        if r[2] in (None, "") and r[1] in (None, ""):  # a group header row (no unit, no quantity)
            group = name
            continue
        kind, attrs = tag(group or "", name)
        key = slug(f"{group or section}-{name}")
        while key in used:
            key += "-2"
        used.add(key)
        rows.append({"key": key, "section": section, "group": group, "name": name, "unit": r[2] or "un",
                     **({"kind": kind, "attrs": attrs} if kind else {})})
    lines = ['"""Master materials checklist — GENERATED by scripts/gen_materials_catalog.py from the "Solicitud de',
             'materiales" workbook. Do not edit by hand; rerun the script. No prices: the BOM is a purchase list."""',
             "", "SECTIONS = " + repr(SECTIONS), "", "CATALOG = ["]
    for row in rows:
        lines.append("    " + repr(row) + ",")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    kinds = {}
    for row in rows:
        kinds[row.get("kind", "-")] = kinds.get(row.get("kind", "-"), 0) + 1
    print(f"{len(rows)} items -> {OUT}\n{kinds}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
