from __future__ import annotations
"""Lista de materiales tab — the project's purchase list (no prices), generated from the saved design.

Generated by `materials/engine.py` from the quote version the Técnico tab reads (same cable lengths,
same PV coupling), then adjusted by the user: roof layout, project options, edited quantities and
hand-added lines, all kept in `projects.tech_spec["materials"]` so a design change never wipes them.
The sheet downloads in the layout of the "Solicitud de materiales" workbook (dealer columns empty).
"""
import uuid

from flask import Response, render_template, request, url_for

from materials import engine
from materials.export_xlsx import build_workbook

CONDUIT_CHOICES = (("PVC", "PVC"), ("EMT", "EMT"), ("none", "Sin tubería"))


def _num(v, default=None, cast=float):
    try:
        out = cast(str(v).replace(",", "."))
        return out if out > 0 else default
    except (TypeError, ValueError):
        return default


def _int(v, default: int = 0) -> int:
    try:
        return max(0, int(float(str(v).replace(",", "."))))
    except (TypeError, ValueError):
        return default


def _build(project: dict):
    from webapp.blueprints import projects_design

    d = projects_design.load(project)
    if d["empty"]:
        return d, None
    return d, engine.build_list(d["eq"], d["wiring"], d["spec"])


def render_panel(ctx: dict, *, message: str | None = None) -> str:
    project = ctx["project"]
    d, result = _build(project)
    if result is None:
        return render_template("projects/_lista.html", pid=project["id"], empty=d["empty"])
    branches = [b for b in (d["wiring"].get("branches") or []) if b.get("conduit") and b.get("key")]
    mats = {**engine.DEFAULT_CONDUIT_MATERIAL, **(result["options"].get("conduit_material") or {})}
    sections: list[dict] = []
    for line in result["lines"]:
        if not sections or sections[-1]["name"] != line["section"]:
            sections.append({"name": line["section"], "groups": []})
        groups = sections[-1]["groups"]
        if not groups or groups[-1]["name"] != (line["group"] or ""):
            groups.append({"name": line["group"] or "", "lines": []})
        groups[-1]["lines"].append(line)
    return render_template(
        "projects/_lista.html", pid=project["id"], empty=None, message=message, sections=sections, result=result,
        layout=result["layout"], options=result["options"], counts=result["counts"],
        chosen=d["chosen"], branches=branches, conduit_mats=mats, conduit_choices=CONDUIT_CHOICES,
        where=engine.WHERE, catalog=engine.catalog_options(), n_lines=sum(1 for ln in result["lines"] if ln["qty"]),
        n_new=sum(1 for ln in result["lines"] if ln["qty"] and not ln["in_master"]),
        coupling=d["wiring"].get("coupling") or {}, custom_lengths=bool(d["spec"].get("wiring_lengths")),
    )


def register(bp):
    @bp.route("/<pid>/lista/guardar", methods=["POST"])
    def lista_guardar(pid):
        """One endpoint for every edit: `action` is inputs | lines | remove | reset | add | reset_all.
        The inputs form and the lines form are separate, so a layout change never reads stale
        quantity fields as overrides."""
        from database.projects_db import get_project, update_tech_spec
        from webapp.blueprints.projects_common import detail_ctx

        project = get_project(pid)
        if not project:
            return render_template("admin/_error.html", message="Proyecto no encontrado.")
        spec = dict(project.get("tech_spec") or {})
        mat = {**(spec.get("materials") or {})}
        form, action = request.form, request.form.get("action", "")

        if action == "inputs":
            layout = {**(mat.get("layout") or {})}
            rows = _num(form.get("layout_rows"), None, lambda s: int(float(s)))
            layout["rows"] = rows
            layout["orientation"] = "landscape" if form.get("layout_orientation") == "landscape" else "portrait"
            layout["rail_len_m"] = _num(form.get("layout_rail_len"), engine.DEFAULT_LAYOUT["rail_len_m"])
            layout["foot_spacing_m"] = _num(form.get("layout_foot"), engine.DEFAULT_LAYOUT["foot_spacing_m"])
            opts = {**(mat.get("options") or {})}
            opts["string_breaker_a"] = _num(form.get("opt_string_breaker"), None, lambda s: int(float(s)))
            opts["bends_per_raceway"] = _int(form.get("opt_bends"), 2)
            opts["lb_per_raceway"] = _int(form.get("opt_lb"), 0)
            cm = {k[4:]: v for k, v in form.items() if k.startswith("mat_") and v in dict(CONDUIT_CHOICES)}
            opts["conduit_material"] = cm
            mat["layout"], mat["options"] = layout, opts
        else:
            overrides = {**(mat.get("overrides") or {})}
            extras = list(mat.get("extras") or [])
            if action == "lines":
                _, result = _build({**project, "tech_spec": spec})
                computed = {ln["id"]: ln for ln in (result["lines"] if result else []) if ln.get("computed_qty") is not None}
                for lid, ln in computed.items():
                    q, comment = form.get("q:" + lid), form.get("c:" + lid)
                    ov = {}
                    if q not in (None, ""):
                        try:
                            val = max(0.0, float(q.replace(",", ".")))
                        except ValueError:
                            val = ln["computed_qty"]
                        if abs(val - ln["computed_qty"]) > 1e-9:
                            ov["qty"] = int(val) if float(val).is_integer() else val
                    if comment is not None and comment.strip() != (ln.get("computed_comment") or "").strip():
                        ov["comment"] = comment.strip()
                    if ov:
                        overrides[lid] = ov
                    else:
                        overrides.pop(lid, None)
                for ex in extras:
                    q = form.get("q:m:" + str(ex["id"]))
                    if q not in (None, ""):
                        ex["qty"] = _num(q, 0.0) or 0.0
                    c = form.get("c:m:" + str(ex["id"]))
                    if c is not None:
                        ex["comment"] = c.strip()
            elif action == "remove":
                lid = form.get("id", "")
                if lid.startswith("m:"):
                    extras = [e for e in extras if "m:" + str(e["id"]) != lid]
                else:
                    overrides[lid] = {**overrides.get(lid, {}), "qty": 0}
            elif action == "reset":
                overrides.pop(form.get("id", ""), None)
            elif action == "reset_all":
                overrides, extras = {}, []
            elif action == "add":
                qty = _num(form.get("add_qty"), 1.0) or 1.0
                key, name = form.get("add_key") or None, (form.get("add_name") or "").strip()
                if key or name:
                    extras.append({"id": uuid.uuid4().hex[:8], "key": key, "name": name or None, "qty": qty,
                                   "unit": (form.get("add_unit") or "un").strip() or "un", "comment": (form.get("add_comment") or "").strip()})
            mat["overrides"], mat["extras"] = overrides, extras
        spec["materials"] = mat
        update_tech_spec(pid, spec)
        return render_panel(detail_ctx(pid, active_tab="lista"))

    @bp.route("/<pid>/lista/descargar")
    def lista_descargar(pid):
        from database.projects_db import get_project

        project = get_project(pid)
        if not project:
            return Response("Proyecto no encontrado.", status=404)
        _, result = _build(project)
        if result is None:
            return Response("Este proyecto no tiene un diseño guardado del cual generar la lista.", status=409)
        name = (project.get("client_name") or "Proyecto").strip()
        data = build_workbook(result["lines"], f"Solicitud de materiales — {name}")
        safe = "".join(ch if ch.isalnum() or ch in " _-" else "" for ch in name).strip().replace(" ", "_") or "Proyecto"
        return Response(data, mimetype="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                        headers={"Content-Disposition": f'attachment; filename="Proyecto_{safe}_Solicitud_de_materiales.xlsx"'})
